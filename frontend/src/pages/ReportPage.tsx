import { useCallback, useEffect, useState } from "react";
import { getReport, regenerateReport, ReportView } from "../api";

const POLL_MS = 2000;

function clock(tMs: number): string {
  const seconds = Math.floor(tMs / 1000);
  return `${String(Math.floor(seconds / 60)).padStart(2, "0")}:${String(seconds % 60).padStart(2, "0")}`;
}

export function ReportPage({ sessionId }: { sessionId: string }) {
  const [view, setView] = useState<ReportView | null>(null);
  const [error, setError] = useState<string | null>(null);

  const load = useCallback(() => {
    getReport(sessionId)
      .then((v) => {
        setView(v);
        setError(null);
      })
      .catch((err) => setError(err instanceof Error ? err.message : String(err)));
  }, [sessionId]);

  useEffect(load, [load]);

  // Poll while the Report is being generated (an interval, so a failed fetch doesn't stop it).
  const generating = view?.status === "generating";
  useEffect(() => {
    if (!generating) return;
    const id = window.setInterval(load, POLL_MS);
    return () => window.clearInterval(id);
  }, [generating, load]);

  const regenerate = () => {
    setView({ status: "generating" });
    regenerateReport(sessionId)
      .then(load)
      .catch((err) => {
        setError(err instanceof Error ? err.message : String(err));
        load();
      });
  };

  return (
    <main className="report">
      <p>
        <a href={`#/sessions/${sessionId}`}>Back to the interview</a>
      </p>
      {error && <p className="error">{error}</p>}
      {!view ? (
        <p>Loading…</p>
      ) : view.status === "generating" ? (
        <p className="report-status">Generating your report… this usually takes under a minute.</p>
      ) : view.status === "report_failed" ? (
        <div className="report-status">
          <p>The report could not be generated.</p>
          <button type="button" onClick={regenerate}>
            Retry
          </button>
        </div>
      ) : view.status === "live" ? (
        <p className="report-status">The interview is still in progress.</p>
      ) : view.status === "ended" || view.status === "abandoned" ? (
        <div className="report-status">
          <p>No report yet.</p>
          <button type="button" onClick={regenerate}>
            Generate report
          </button>
        </div>
      ) : view.status === "report_ready" ? (
        <ReadyReport view={view} />
      ) : null}
    </main>
  );
}

function ReadyReport({ view }: { view: Extract<ReportView, { status: "report_ready" }> }) {
  const { report, usage } = view;
  const signal = report.overall_signal;
  return (
    <>
      <h1>Interview report</h1>
      <section className="signal">
        <span className={`signal-label signal-${signal.label.replace(/ /g, "-").toLowerCase()}`}>
          {signal.label}
        </span>
        <span className="hint">
          weighted average {signal.weighted_average.toFixed(2)} / 4
          {signal.capped && " (capped at No by a 1 in Testing or Correctness)"}
        </span>
        <p>{signal.rationale}</p>
      </section>
      <p className="summary">{report.summary}</p>
      <table className="rubric">
        <thead>
          <tr>
            <th>Dimension</th>
            <th>Score</th>
            <th>Evidence</th>
          </tr>
        </thead>
        <tbody>
          {report.rubric.map((row) => (
            <tr key={row.dimension}>
              <td>
                <strong>{row.label}</strong>
                {row.weight > 1 && <span className="hint"> ({row.weight}×)</span>}
                {row.note && <div className="hint">{row.note}</div>}
              </td>
              <td className={`score score-${row.score}`}>{row.score}</td>
              <td>
                <ul>
                  {row.evidence.map((e, i) => (
                    <li key={i}>
                      <span className="stamp">{clock(e.t_ms)}</span>{" "}
                      <q>{e.quote_or_code}</q> {e.comment}
                    </li>
                  ))}
                </ul>
              </td>
            </tr>
          ))}
        </tbody>
      </table>
      <p className="hint">
        Generated by {view.model}
        {usage &&
          ` · ${usage.input_tokens + usage.cache_read_input_tokens + usage.cache_creation_input_tokens} input / ${usage.output_tokens} output tokens` +
            (usage.attempts > 1 ? ` · ${usage.attempts} attempts` : "")}
      </p>
    </>
  );
}

import { useCallback, useEffect, useState } from "react";
import {
  CandidateTest,
  getReport,
  IdealWalkthrough,
  Improvement,
  Metrics,
  regenerateReport,
  ReportView,
  Strength,
  TestingBreakdown,
} from "../api";

const POLL_MS = 2000;

function clock(tMs: number): string {
  const seconds = Math.floor(tMs / 1000);
  return `${String(Math.floor(seconds / 60)).padStart(2, "0")}:${String(seconds % 60).padStart(2, "0")}`;
}

export function ReportPage({ sessionId }: { sessionId: string }) {
  const [view, setView] = useState<ReportView | null>(null);
  const [error, setError] = useState<string | null>(null);

  const load = useCallback(() => {
    getReport(sessionId)
      .then((v) => {
        setView(v);
        setError(null);
      })
      .catch((err) => setError(err instanceof Error ? err.message : String(err)));
  }, [sessionId]);

  useEffect(load, [load]);

  // Poll while the Report is being generated (an interval, so a failed fetch doesn't stop it).
  const generating = view?.status === "generating";
  useEffect(() => {
    if (!generating) return;
    const id = window.setInterval(load, POLL_MS);
    return () => window.clearInterval(id);
  }, [generating, load]);

  const regenerate = () => {
    setView({ status: "generating" });
    regenerateReport(sessionId)
      .then(load)
      .catch((err) => {
        setError(err instanceof Error ? err.message : String(err));
        load();
      });
  };

  return (
    <main className="report">
      <p>
        <a href={`#/sessions/${sessionId}`}>Back to the interview</a>
      </p>
      {error && <p className="error">{error}</p>}
      {!view ? (
        <p>Loading…</p>
      ) : view.status === "generating" ? (
        <p className="report-status">Generating your report… this usually takes under a minute.</p>
      ) : view.status === "report_failed" ? (
        <div className="report-status">
          <p>The report could not be generated.</p>
          <button type="button" onClick={regenerate}>
            Retry
          </button>
        </div>
      ) : view.status === "live" ? (
        <p className="report-status">The interview is still in progress.</p>
      ) : view.status === "ended" || view.status === "abandoned" ? (
        <div className="report-status">
          <p>No report yet.</p>
          <button type="button" onClick={regenerate}>
            Generate report
          </button>
        </div>
      ) : view.status === "report_ready" ? (
        <ReadyReport view={view} />
      ) : null}
    </main>
  );
}

function ReadyReport({ view }: { view: Extract<ReportView, { status: "report_ready" }> }) {
  const { report, usage, metrics } = view;
  const signal = report.overall_signal;
  return (
    <>
      <h1>Interview report</h1>
      <section className="signal">
        <span className={`signal-label signal-${signal.label.replace(/ /g, "-").toLowerCase()}`}>
          {signal.label}
        </span>
        <span className="hint">
          weighted average {signal.weighted_average.toFixed(2)} / 4
          {signal.capped && " (capped at No by a 1 in Testing or Correctness)"}
          {report.autocomplete !== undefined &&
            ` · editor autocomplete ${report.autocomplete ? "on" : "off"}`}
        </span>
        <p>{signal.rationale}</p>
      </section>
      <p className="summary">{report.summary}</p>
      <table className="rubric">
        <thead>
          <tr>
            <th>Dimension</th>
            <th>Score</th>
            <th>Evidence</th>
          </tr>
        </thead>
        <tbody>
          {report.rubric.map((row) => (
            <tr key={row.dimension}>
              <td>
                <strong>{row.label}</strong>
                {row.weight > 1 && <span className="hint"> ({row.weight}×)</span>}
                {row.note && <div className="hint">{row.note}</div>}
              </td>
              <td className={`score score-${row.score}`}>{row.score}</td>
              <td>
                <ul>
                  {row.evidence.map((e, i) => (
                    <li key={i}>
                      <span className="stamp">{clock(e.t_ms)}</span>{" "}
                      <q>{e.quote_or_code}</q> {e.comment}
                    </li>
                  ))}
                </ul>
              </td>
            </tr>
          ))}
        </tbody>
      </table>
      {report.strengths && report.improvements && (
        <FeedbackSection strengths={report.strengths} improvements={report.improvements} />
      )}
      {report.testing && <TestingSection testing={report.testing} />}
      <MetricsSection metrics={metrics} />
      {report.ideal_walkthrough && <WalkthroughSection walkthrough={report.ideal_walkthrough} />}
      <p className="hint">
        Generated by {view.model}
        {usage &&
          ` · ${usage.input_tokens + usage.cache_read_input_tokens + usage.cache_creation_input_tokens} input / ${usage.output_tokens} output tokens` +
            (usage.attempts > 1 ? ` · ${usage.attempts} attempts` : "")}
      </p>
    </>
  );
}

function TestRow({ test }: { test: CandidateTest }) {
  return (
    <li>
      <span className="stamp">{clock(test.t_ms)}</span> <code>{test.input}</code>{" "}
      <span className="hint">
        {test.kind}
        {test.form === "stdin" && ", stdin"}
        {test.outcome === "failed" && ", stopped the run"}
        {test.kind === "executed" && test.runs > 1 && `, ${test.runs} runs`}
        {", "}
        {test.verified ? "verified" : "unverified"}
        {test.expected_result && ` (expected ${test.expected_result})`}
      </span>
    </li>
  );
}

function TestingSection({ testing }: { testing: TestingBreakdown }) {
  const { totals } = testing;
  return (
    <section className="testing">
      <h2>Your tests</h2>
      <p className="hint">
        {totals.executed} executed, {totals.traced} traced, {totals.verified} with a stated expected
        result.
      </p>
      {testing.groups.map((group) => (
        <div key={group.category}>
          <h3>{group.category}</h3>
          <ul>
            {group.tests.map((t) => (
              <TestRow key={t.id} test={t} />
            ))}
          </ul>
        </div>
      ))}
      {testing.ran_but_not_verified.length > 0 && (
        <div>
          <h3>Ran but not verified</h3>
          <p className="hint">You never said or wrote what these should produce.</p>
          <ul>
            {testing.ran_but_not_verified.map((t) => (
              <TestRow key={t.id} test={t} />
            ))}
          </ul>
        </div>
      )}
      <h3>Edge-case categories you missed</h3>
      {testing.missed_categories.length === 0 ? (
        <p>None: your tests touched every category.</p>
      ) : (
        <ul>
          {testing.missed_categories.map((c) => (
            <li key={c.name}>
              <strong>{c.name}</strong> {c.description}
            </li>
          ))}
        </ul>
      )}
    </section>
  );
}

function FeedbackSection({
  strengths,
  improvements,
}: {
  strengths: Strength[];
  improvements: Improvement[];
}) {
  return (
    <section className="feedback">
      <h2>Top strengths</h2>
      <ol>
        {strengths.map((s, i) => (
          <li key={i}>
            <strong>{s.title}</strong> {s.detail}
          </li>
        ))}
      </ol>
      <h2>Top improvements</h2>
      <ol>
        {improvements.map((s, i) => (
          <li key={i}>
            <strong>{s.title}</strong> {s.detail}
            <div>
              <strong>Drill:</strong> {s.drill}
            </div>
          </li>
        ))}
      </ol>
    </section>
  );
}

function duration(ms: number | null | undefined): string {
  return ms == null ? "never" : clock(ms);
}

function MetricsSection({ metrics }: { metrics: Partial<Metrics> }) {
  const m = metrics;
  const hints = Object.entries(m.hints_by_level ?? {})
    .map(([level, n]) => `L${level}: ${n}`)
    .join(", ");
  const errors = Object.entries(m.error_types ?? {})
    .map(([name, n]) => `${name} ×${n}`)
    .join(", ");
  return (
    <section className="metrics">
      <h2>Metrics</h2>
      <ul>
        <li>First code at {duration(m.time_to_first_code_ms)}, first Run at {duration(m.time_to_first_run_ms)}, first test at {duration(m.time_to_first_test_ms)}</li>
        <li>
          {m.runs ?? 0} Runs, {m.failed_runs ?? 0} failed{errors && ` (${errors})`}
        </li>
        <li>
          Silences over 60 s:{" "}
          {m.silence_gaps?.length
            ? m.silence_gaps.map((g) => `${clock(g.start_ms)} to ${clock(g.end_ms)}`).join(", ")
            : "none"}
        </li>
        <li>
          You spoke {m.candidate_words ?? 0} words, the Interviewer {m.interviewer_words ?? 0}
          {m.candidate_talk_ratio != null && ` (you: ${Math.round(m.candidate_talk_ratio * 100)}%)`}
          {m.coding_words_per_minute != null && `; ${m.coding_words_per_minute} words/min while coding`}
        </li>
        <li>Hints by level: {hints || "none"}</li>
        <li>
          Large pastes:{" "}
          {m.large_pastes?.length
            ? m.large_pastes.map((p) => `${p.length} chars at ${clock(p.t_ms)}`).join(", ")
            : "none"}{" "}
          <span className="hint">(noted, never scored)</span>
        </li>
        {!!m.muted_ms && <li>Time muted: {clock(m.muted_ms)}</li>}
      </ul>
    </section>
  );
}

function WalkthroughSection({ walkthrough }: { walkthrough: IdealWalkthrough }) {
  return (
    <section className="walkthrough">
      <h2>Ideal walkthrough</h2>
      <p>{walkthrough.approach}</p>
      <p>
        <strong>Complexity:</strong> {walkthrough.complexity}
      </p>
      <details>
        <summary>Reveal ideal walkthrough code</summary>
        <pre>
          <code>{walkthrough.code}</code>
        </pre>
      </details>
    </section>
  );
}
